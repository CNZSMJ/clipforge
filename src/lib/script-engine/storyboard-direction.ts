export function buildStoryboardDirection(input: {
  contentType: "product" | "topic";
  targetDuration: number;
  videoMode?: string;
}): string {
  const seconds = Number.isFinite(input.targetDuration) && input.targetDuration > 0 ? input.targetDuration : 25;
  const mode = input.videoMode ?? "product_closeup";
  const production = input.contentType === "topic"
    ? `【主题素材边界】优先真实可检索镜头。searchTerms 保留每镜真正的主体、地点与动作，检索词不是文案。需同一人物/地点连续表演时使用同源素材；否则围绕匿名物件或环境建立概念连续性，不宣称库存片能保证身份一致。`
    : `【约束优先级】事实与参考图、视频模式的人物/素材边界优先；用户明确的创作媒介与要求优先于默认风格、历史表现和示例。当前模式 ${mode}。人物禁入模式只允许画外说话，不因戏剧/采访/口播风格自动放入人物。product_image 只能裁切、平移、缩放、后期贴字，不描述原图不存在的新视角、内部结构或物理演示。`;
  return `${COMMON_DIRECTION}\n${production}\n【时间预算】目标总时长 ${seconds}秒；各镜 duration 总和等于 totalDuration 并贴合目标，不再受通用示例的25秒限制。以必要的信息/动作选择镜数，通常每镜2–6秒，关键动作可更长；有参考镜头结构时优先保留其节奏边界。中文旁白约每秒3个可说字符、英文约每秒2个词作初稿预算，预留停顿，绝不是强制填满。`;
}

